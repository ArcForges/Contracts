"""DP-03 generated local-operation decoders for the boundary dispatch assembly (CON.43, S61(1)).

The pinned generator reads only reviewed repository inputs:

- the compiled closure descriptor set ``artifacts/local-dispatch.binpb`` (written by ``eng/contracts.py
  generate`` from the catalog row of ArcForges.Contracts.LocalRpc.Dispatch), read through the repository's
  own descriptor reader ``check_compatibility.descriptor``;
- the merged constraint snapshots ``public/proto/constraints.json`` and ``internal/proto/constraints.json``;
- the operation-metadata.v1 rows of ``eng/operations`` and the operation-scope manifest, through the
  operation-scope gate ``check_operation_scope`` (no second validator);
- the closed in-process port list ``con06_inprocess.PORTS``.

For every tool-eligible IScopeOperations and IChatOperations method (registry 04: the section 6 Scope and
Chat methods minus the AZ-04 human-only decisions) it emits into
``src/internal/dotnet/ArcForges.Contracts.LocalRpc.Dispatch/Generated/Operations`` the request and result
schema, the non-reflective decoder from CapabilityArguments to the typed request, the result encoder to
CapabilityResult and their symmetric legs. The closed allowlist holds an entry only for an operation the
operation-scope gate admits as a tool row (authorization.capability equal to its exact operation ID and the
agent actor reachable through the gate); an eligible name or a generated port alone admits nothing.
Infrastructure-port methods are not model-callable and get nothing. The output is deterministic and uses no
reflection, runtime registry or name-keyed dictionary (DP-04, DP-06).
"""
