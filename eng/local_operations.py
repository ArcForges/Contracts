class GenerationError(ValueError):
    """A refused input; nothing is written when this is raised."""


def require(value: bool, message: str) -> None:
    if not value:
        raise GenerationError(message)


def ordinal(value: str) -> bytes:
    """Sort key equal to .NET StringComparer.Ordinal (UTF-16 code units)."""
    return value.encode("utf-16-be", "surrogatepass")


def ordered(values) -> list:
    return sorted(values, key=ordinal)


def literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def canonical(value) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def pascal(value: str) -> str:
    """protoc C# UnderscoresToPascalCase."""
    result, cap_next = [], True
    for index, character in enumerate(value):
        if "a" <= character <= "z":
            result.append(character.upper() if cap_next else character)
            cap_next = False
        elif "A" <= character <= "Z":
            result.append(character.lower() if index == 0 and not cap_next else character)
            cap_next = False
        elif "0" <= character <= "9":
            result.append(character)
            cap_next = True
        else:
            cap_next = True
    return "".join(result)


def long_literal(value: int) -> str:
    return "long.MinValue" if value == INT64_MIN else "long.MaxValue" if value == INT64_MAX else f"{value}L"


def symbol(full_name: str) -> str:
    return "".join(pascal(part) for part in full_name.lstrip(".").split("."))


