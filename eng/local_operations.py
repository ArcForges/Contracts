def render(inputs: Inputs) -> dict[str, str]:
    """Pure: the complete output file set (repository-relative POSIX path to LF text)."""
    return Emitter(inputs).render()


def sync(files: dict[str, str], root: Path, check: bool) -> None:
    """Write (or with ``check`` verify) exactly ``files`` under the output directory; stale files are removed or refused."""
    require(all(path.startswith(OUTPUT + "/") for path in files), "generated path outside " + OUTPUT)
    target = root / OUTPUT
    expected = {path: content.encode("utf-8") for path, content in files.items()}
    actual = {}
    if target.is_dir():
        for path in sorted(target.rglob("*"), key=lambda p: ordinal(p.as_posix())):
            if path.is_file():
                actual[path.relative_to(root).as_posix()] = path.read_bytes()
    if check:
        changed = ordered(path for path in expected.keys() | actual.keys() if expected.get(path) != actual.get(path))
        require(not changed, "Stale generated local operations: " + ", ".join(changed))
        return
    for path in ordered(actual.keys() - expected.keys()):
        (root / path).unlink()
    for path in ordered(expected):
        destination = root / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        if actual.get(path) != expected[path]:
            destination.write_bytes(expected[path])


def generate(check: bool = False, root: Path = ROOT) -> None:
    """Emit (or with ``check`` verify) the complete generated operation set."""
    sync(render(load_inputs(root)), root, check)


def main(argv: list[str] | None = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        generate(args.check)
    except (ValueError, KeyError, OSError) as error:
        print(f"Local operation generation failed: {error}", file=sys.stderr)
        return 1
    print("Generated local operations match." if args.check else "Generated local operations.")
    return 0


