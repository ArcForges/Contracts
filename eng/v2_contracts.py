def specifications(root: Path = ROOT):
    manifest = json.loads((root / "eng/afv2-contracts.json").read_text())
    for row in manifest["files"]:
        data = (root / row["path"]).read_bytes().replace(b"\r\n", b"\n")
        if hashlib.sha256(data).hexdigest() != row["sha256"]:
            raise ValueError("V2 specification differs from reviewed adoption: " + row["path"])
        yield row, data.decode()


def messages(domain: str):
    result = {}
    for row, text in specifications():
        package = re.search(r"package ([\w.]+);", text)[1]
        if package != "arcforges." + domain + ".v2":
            continue
        for name, body in re.findall(r"message (\w+) \{(.*?)\n\}", text, re.S):
            fields = {}
            for label, kind, name_field, tag, key in re.findall(r'(?:(optional|repeated) )?([\w.]+) (\w+) = (\d+) \[json_name = "([^"]+)"\];', body):
                fields[key] = {"label": label, "type": kind, "name": name_field, "tag": int(tag)}
            groups = {group: re.findall(r"[\w.]+ (\w+) =", values) for group, values in re.findall(r"oneof (\w+) \{([^}]+)\}", body)}
            result[name] = {"fields": fields, "oneofs": groups}
    return result


def methods(root: Path = ROOT):
    from check_operation_scope import flagship_annotations
    rows = []
    if not (root / "eng/afv2-contracts.json").exists():
        return rows
    for source, text in specifications(root):
        types = {name: body for name, body in re.findall(r"message (\w+) \{(.*?)\n\}", text, re.S)}
        annotated = flagship_annotations(text, source["path"])
        for binding, annotation in annotated.items():
            name = binding.rsplit("/", 1)[1]
            match = re.search(r"rpc " + name + r"\((\w+)\) returns \((stream )?(\w+)\)", text)
            request, streamed, response = match.groups()
            transient = "transient live-lease" in annotation["idempotency"]
            durable = "durable owner+owner_epoch" in annotation["idempotency"] or (binding.endswith("DeviceService/Revoke"))
            kind = "transient_terminal" if transient else "durable_node" if durable and "sandbox.v2" in binding else "durable_center" if durable else "read"
            owner_epoch = "owner_epoch = 100" in types[request]
            if owner_epoch != (kind == "durable_node") or transient and (owner_epoch or annotation["locality"] != "local only"):
                raise ValueError("Invalid V2 epoch/locality classification: " + binding)
            rows.append({"binding": binding, "source": source["path"], "request": request, "response": response,
                         "kind": kind, "localOnly": annotation["locality"] == "local only", "ownerEpoch": owner_epoch,
                         "serverStreaming": bool(streamed), "reconciliation": "none" if transient else "NodeService.GetOperation" if kind == "durable_node" else "read_only" if kind == "read" else "Center receipt",
                         "annotations": annotation})
    return sorted(rows, key=lambda x: x["binding"])


