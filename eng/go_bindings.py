def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def say(message: str) -> None:
    print(message, flush=True)


# ------------------------------------------------------------------------------------------------ toolchain and runs

def environment(extra: dict | None = None) -> dict:
    env = dict(os.environ, GOTOOLCHAIN="local", GOFLAGS="-mod=readonly", GOTELEMETRY="off", GOWORK="off")
    env.update(extra or {})
    return env


def run(*args: object, cwd: Path = MODULE, capture: bool = False, env: dict | None = None, check: bool = True):
    command = [str(arg) for arg in args]
    print("+ " + " ".join(command), flush=True)
    result = subprocess.run(command, cwd=cwd, env=env or environment(), text=True, encoding="utf-8",
                            errors="replace", capture_output=capture)
    if check and result.returncode != 0:
        if capture:
            sys.stdout.write(result.stdout)
            sys.stderr.write(result.stderr)
        raise subprocess.CalledProcessError(result.returncode, command)
    return result


def go(*args: object, cwd: Path = MODULE, capture: bool = False, env: dict | None = None) -> str:
    return run("go", *args, cwd=cwd, capture=capture, env=env).stdout or ""


def pinned_toolchain() -> dict:
    value = json.loads(TOOLCHAIN.read_text(encoding="utf-8"))
    require(set(value) == {"goVersion", "linuxAmd64", "windowsAmd64"}
            and re.fullmatch(r"go1\.[0-9]+\.[0-9]+", value["goVersion"]) is not None, "Invalid go/toolchain.json")
    for key in ("linuxAmd64", "windowsAmd64"):
        archive = value[key]
        require(set(archive) == {"url", "sha256"} and archive["url"].startswith("https://go.dev/dl/" + value["goVersion"] + ".")
                and re.fullmatch("[0-9a-f]{64}", archive["sha256"]) is not None, "Invalid pinned Go archive: " + key)
    return value


def go_mod(module: Path) -> dict:
    """The directives of one go.mod that the checks rely on."""
    text = (module / "go.mod").read_text(encoding="utf-8")
    name = re.search(r"^module (\S+)$", text, re.M)
    version = re.search(r"^go (\S+)$", text, re.M)
    requires = dict(re.findall(r"^\t?(?:require )?([a-z0-9.\-]+\.[a-z]{2,}/\S+) (v\S+)(?: // indirect)?$", text, re.M))
    tools = re.findall(r"^\t?(?:tool )?([a-z0-9.\-]+\.[a-z]{2,}/\S+)$", text, re.M)
    return {"module": name[1] if name else None, "go": version[1] if version else None, "requires": requires,
            "tools": tools, "toolchain": re.search(r"^toolchain ", text, re.M) is not None,
            "replace": re.search(r"^\s*replace\b", text, re.M) is not None,
            "exclude": re.search(r"^\s*exclude\b", text, re.M) is not None}


def check_modules() -> dict:
    """Both go.mod files: the pinned language version, no toolchain/replace/exclude, runtime versions aligned."""
    pinned = pinned_toolchain()["goVersion"]
    main, tools = go_mod(MODULE), go_mod(TOOLS)
    for label, value, expected in (("go/go.mod", main, GO_MODULE), ("go/tools/go.mod", tools, TOOLS_MODULE)):
        require(value["module"] == expected, f"{label} must declare module {expected}")
        require("go" + str(value["go"]) == pinned, f"{label} must declare go {pinned.removeprefix('go')}")
        require(not value["toolchain"] and not value["replace"] and not value["exclude"],
                f"{label} must not carry toolchain, replace or exclude directives")
        require(not any(path.startswith("github.com/ArcForges/") for path in value["requires"]),
                f"{label} must not require first-party Go modules")
    require(sorted(main["requires"]) == sorted(RUNTIME),
            "The published Go module requires exactly " + ", ".join(RUNTIME) + "; review any other requirement")
    require(not main["tools"], "The published Go module declares no tool dependency; tools live in go/tools")
    require(sorted(tools["tools"]) == sorted(TOOL_PACKAGES.values()), "go/tools must pin exactly the reviewed tools")
    for path in RUNTIME:
        require(tools["requires"].get(path) == main["requires"][path],
                f"{path}: go/tools generates with {tools['requires'].get(path)} but go/go.mod requires "
                f"{main['requires'][path]}; update both modules together")
    return {"go": pinned, "runtime": {path: main["requires"][path] for path in RUNTIME},
            "tools": {name: tools["requires"].get(package.split("/cmd/")[0]) for name, package in TOOL_PACKAGES.items()}}


def check_toolchain() -> str:
    pinned = pinned_toolchain()["goVersion"]
    output = go("version", capture=True).split()
    require(len(output) >= 3 and output[2] == pinned,
            f"Install the pinned {pinned} (go/toolchain.json) on this host; found {' '.join(output[2:3]) or 'no go'}")
    return pinned


def build_tools(directory: Path, names: tuple[str, ...] = tuple(TOOL_PACKAGES)) -> dict[str, Path]:
    """Build the pinned tools of go/tools into directory (module sources verified by go/tools/go.sum)."""
    directory.mkdir(parents=True, exist_ok=True)
    go("build", "-trimpath", "-o", str(directory) + os.sep, *(TOOL_PACKAGES[name] for name in names), cwd=TOOLS)
    suffix = ".exe" if os.name == "nt" else ""
    result = {name: directory / (name + suffix) for name in names}
    for name, path in result.items():
        require(path.is_file(), "Pinned Go tool was not built: " + name)
    return result


def install_toolchain(destination: Path) -> Path:
    """Hosted CI only: download the pinned Go archive, verify its SHA-256 and extract it; returns GOROOT/bin."""
    value = pinned_toolchain()
    key = {"Linux": "linuxAmd64", "Windows": "windowsAmd64"}.get(platform.system())
    require(key is not None and platform.machine().lower() in {"amd64", "x86_64"},
            "The pinned Go archives cover x64 Linux and Windows only")
    archive = value[key]
    with urlopen(Request(archive["url"], headers={"User-Agent": "ArcForges-Contracts-CI"}), timeout=300) as response:
        data = response.read()
    actual = hashlib.sha256(data).hexdigest()
    require(actual == archive["sha256"], f"Go archive SHA-256 mismatch: {actual}")
    destination.mkdir(parents=True, exist_ok=True)
    if archive["url"].endswith(".zip"):
        with zipfile.ZipFile(io.BytesIO(data)) as bundle:
            bundle.extractall(destination)
    else:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as bundle:
            bundle.extractall(destination, filter="data")
    binary = destination / "go" / "bin"
    say(f"Installed {value['goVersion']} ({archive['sha256']}) in {binary}")
    return binary


# ------------------------------------------------------------------------------------------------------- generation

def go_row(root: Path = ROOT) -> dict:
    from package_catalog import packages
    rows = packages("go", root)
    require(len(rows) == 1, "Exactly one Go module row is registered in eng/contract-packages.json")
    return rows[0]


def mapping_options(row: dict) -> list[str]:
    """protoc M options: each generated proto file to its Go import path and package name."""
    by_directory = {item["importPath"].removeprefix(GO_MODULE + "/"): item for item in row["goPackages"]}
    options = []
    for source in row["proto"]:
        virtual = source.split("/proto/", 1)[1]
        item = by_directory[virtual.rsplit("/", 1)[0]]
        options.append(f"M{virtual}={item['importPath']};{item['name']}")
    return options


def protoc_includes(row: dict) -> list[object]:
    roots = sorted({source.split("/proto/", 1)[0] for source in row["proto"]}, key=lambda name: name != "public")
    return [argument for name in roots for argument in ("-I", ROOT / name / "proto")]


def write_descriptor(protoc: Path, row: dict) -> Path:
    """The compiled descriptor set of the Go module's proto closure (the candidate's go-module.binpb)."""
    ARTIFACTS.mkdir(exist_ok=True)
    target = ARTIFACTS / row["descriptor"]
    with tempfile.TemporaryDirectory(prefix="go-descriptor-", dir=ARTIFACTS) as temporary:
        arguments = Path(temporary) / "protoc.args"
        arguments.write_text("\n".join(str(argument) for argument in [
            *protoc_includes(row), "--include_imports", f"--descriptor_set_out={target}",
            *(ROOT / source for source in row["proto"])]) + "\n", encoding="utf-8")
        run(protoc, "@" + str(arguments), cwd=ROOT)
    return target


def package_doc(name: str, item: dict, connect: bool) -> str:
    """doc.go of one generated package: its contract identity and access boundary, generated from the row."""
    access = item["contractAccess"]
    lines = [f"Package {name} holds the generated Connect clients and handlers of the services of the ArcForges"
             f" contract package {item['protoPackage']}." if connect else
             f"Package {name} holds the generated protobuf messages of the ArcForges contract package"
             f" {item['protoPackage']}.",
             "",
             "It is generated from the .proto files of the ArcForges Contracts repository by protoc-gen-go and"
             " protoc-gen-connect-go through python eng/contracts.py generate, and never edited by hand.",
             ""]
    if access == "internal":
        lines.append(f"Contract access: internal. {item['protoPackage']} is an internal ArcForges contract: only"
                     " first-party ArcForges services (the center) may import this package. Go's internal/ directory"
                     " rule is not used because the center is a separate module, so this boundary is a contract-access"
                     " policy, recorded in eng/contract-packages.json.")
    else:
        lines.append(f"Contract access: public contract, published in the internal-access module {GO_MODULE} for the"
                     " ArcForges center (AD-0021). Business clients use the C# NuGet packages, the only first-party"
                     " SDK channel (CON.40).")
    wrapped = []
    for line in lines:
        words, current = line.split(), ""
        if not words:
            wrapped.append("//")
            continue
        for word in words:
            if current and len(current) + 1 + len(word) > 110:
                wrapped.append("// " + current)
                current = word
            else:
                current = f"{current} {word}" if current else word
        wrapped.append("// " + current)
    return ("// SPDX-License-Identifier: Apache-2.0\n\n"
            "// Code generated by eng/contracts.py from eng/contract-packages.json. DO NOT EDIT.\n\n"
            + "\n".join(wrapped) + f"\npackage {name}\n")


def write_package_docs(output: Path, row: dict) -> None:
    by_directory = {item["importPath"].removeprefix(GO_MODULE + "/"): item for item in row["goPackages"]}
    for directory in sorted({path.parent for path in (output / GENERATED).rglob("*.go")}):
        relative = directory.relative_to(output).as_posix()
        names = {re.search(r"^package (\w+)$", path.read_text(encoding="utf-8"), re.M)[1]
                 for path in directory.glob("*.go")}
        require(len(names) == 1, "Generated directory holds more than one Go package: " + relative)
        name = names.pop()
        connect = relative not in by_directory
        item = by_directory[relative.rsplit("/", 1)[0] if connect else relative]
        require(name == (item["name"] + "connect" if connect else item["name"]),
                f"Generated Go package name differs from the mapping: {relative}: {name}")
        (directory / "doc.go").write_bytes(package_doc(name, item, connect).encode("utf-8"))


def validate_output(output: Path, row: dict) -> None:
    files = sorted(path for path in output.rglob("*") if path.is_file())
    require(files, "protoc produced no Go bindings")
    for path in files:
        relative = path.relative_to(output).as_posix()
        require(relative.startswith(GENERATED + "/") and relative.endswith((".pb.go", ".connect.go", "/doc.go")),
                "Unexpected generator output: " + relative)
        data = path.read_bytes()
        require(b"\r" not in data and data.endswith(b"\n"), "Generated Go must be LF-terminated: " + relative)
        text = data.decode("utf-8")
        require(text.startswith("// SPDX-License-Identifier: Apache-2.0\n") and GENERATED_HEADER.search(text),
                "Generated Go lacks its licence or generated-code header: " + relative)
    expected = {source.split("/proto/", 1)[1][:-len(".proto")] + ".pb.go" for source in row["proto"]}
    actual = {path.relative_to(output).as_posix() for path in files if path.name.endswith(".pb.go")}
    require(actual == expected, "Generated message files differ from the row's proto files")


def generate(check: bool, protoc: Path) -> None:
    """Regenerate go/arcforges from the row's proto files with the pinned plugins; --check refuses any difference."""
    check_toolchain()
    check_modules()
    row = go_row()
    from contracts import sync_generated
    ARTIFACTS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="go-generate-", dir=ARTIFACTS) as temporary:
        stage = Path(temporary)
        tools = build_tools(stage / "bin", ("protoc-gen-go", "protoc-gen-connect-go"))
        output = stage / "out"
        output.mkdir()
        options = "paths=source_relative," + ",".join(mapping_options(row))
        # One argument per line in a protoc argument file: the M options stay out of the command line (and its
        # Windows length limit) and out of the log.
        arguments = stage / "protoc.args"
        arguments.write_text("\n".join(str(argument) for argument in [
            *protoc_includes(row),
            f"--plugin=protoc-gen-go={tools['protoc-gen-go']}",
            f"--plugin=protoc-gen-connect-go={tools['protoc-gen-connect-go']}",
            f"--go_out={output}", f"--go_opt={options}",
            f"--connect-go_out={output}", f"--connect-go_opt={options}",
            *(ROOT / source for source in row["proto"])]) + "\n", encoding="utf-8")
        say(f"Generating {len(row['proto'])} proto files into {len(row['goPackages'])} Go packages "
            f"({protoc_version(protoc)}, {go_mod(TOOLS)['requires']['google.golang.org/protobuf']} protoc-gen-go, "
            f"{go_mod(TOOLS)['requires']['connectrpc.com/connect/v2']} protoc-gen-connect-go)")
        run(protoc, "@" + str(arguments), cwd=ROOT)
        write_package_docs(output, row)
        validate_output(output, row)
        sync_generated(output / GENERATED, MODULE / GENERATED, check)
    write_descriptor(protoc, row)
    say("Go bindings match the authored proto." if check else "Generated the Go bindings in go/" + GENERATED + ".")


def protoc_version(protoc: Path) -> str:
    return run(protoc, "--version", capture=True, cwd=ROOT).stdout.strip()


