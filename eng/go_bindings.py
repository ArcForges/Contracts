# ---------------------------------------------------------------------------------------------------- static checks

def tracked_go_files() -> list[str]:
    output = subprocess.check_output(["git", "-C", str(ROOT), "ls-files", "-z", "--cached", "--others",
                                      "--exclude-standard", "--", "go"], text=True, encoding="utf-8")
    return sorted(path for path in output.split("\0") if path)


def check_sources() -> dict:
    """The module's file inventory: generated packages, the offline tests and module metadata only."""
    files = tracked_go_files()
    allowed = {"go/go.mod", "go/go.sum", "go/LICENSE", "go/NOTICE", "go/README.md", "go/toolchain.json",
               "go/tools/go.mod", "go/tools/go.sum"}
    handwritten = []
    for path in files:
        if path.startswith(f"go/{GENERATED}/"):
            require(path.endswith(".go"), "Only generated Go belongs in go/" + GENERATED + ": " + path)
            continue
        if path.startswith("go/" + HANDWRITTEN):
            require(path.endswith(".go"), "Only Go test sources belong in go/" + HANDWRITTEN + ": " + path)
            handwritten.append(path)
            continue
        require(path in allowed, "Unreviewed file in the Go module: " + path)
    for path in handwritten:
        text = (ROOT / path).read_text(encoding="utf-8")
        require(text.startswith("// SPDX-License-Identifier: Apache-2.0\n"), "Missing SPDX header: " + path)
        require(not GENERATED_HEADER.search(text), "Handwritten Go must not claim to be generated: " + path)
        if not path.endswith("_test.go"):
            for forbidden in FORBIDDEN_IMPORTS:
                require(f'"{forbidden}"' not in text, f"{path}: {forbidden} is test-only (WP03.02)")
    for path in files:
        if path.startswith(f"go/{GENERATED}/"):
            text = (ROOT / path).read_text(encoding="utf-8")
            for forbidden in FORBIDDEN_IMPORTS:
                require(f'"{forbidden}"' not in text, f"{path}: generated code imports {forbidden} (WP03.02)")
    return {"files": len(files), "handwritten": handwritten}


def gofmt() -> Path:
    root = go("env", "GOROOT", capture=True).strip()
    return Path(root) / "bin" / ("gofmt.exe" if os.name == "nt" else "gofmt")


def check_access() -> int:
    """Go imports keep the contract-access graph: a public contract package never imports an internal one."""
    row = go_row()
    access = {item["importPath"]: item["contractAccess"] for item in row["goPackages"]}
    for item in row["goPackages"]:
        access[item["importPath"] + "/" + item["name"] + "connect"] = item["contractAccess"]
    output = go("list", "-json=ImportPath,Imports", "./" + GENERATED + "/...", capture=True)
    decoder, count = json.JSONDecoder(), 0
    while output.strip():
        output = output.lstrip()
        package, end = decoder.raw_decode(output)
        output = output[end:]
        own = access.get(package["ImportPath"])
        require(own is not None, "Generated Go package has no contract-access row: " + package["ImportPath"])
        for imported in package.get("Imports", []):
            if imported.startswith(GO_MODULE + "/"):
                require(imported in access, "Unmapped first-party Go import: " + imported)
                require(own == "internal" or access[imported] == "public",
                        f"Public contract package {package['ImportPath']} imports internal {imported}")
        count += 1
    require(count > 0, "No generated Go package was listed")
    return count


def static() -> dict:
    """gofmt, the module inventory, go mod verify and tidy drift (both modules), go vet, the access graph, staticcheck."""
    pinned = check_toolchain()
    modules = check_modules()
    sources = check_sources()
    unformatted = run(gofmt(), "-l", ".", capture=True).stdout.strip()
    require(not unformatted, "Unformatted Go sources (gofmt -l):\n" + unformatted)
    for module in (MODULE, TOOLS):
        go("mod", "verify", cwd=module)
        drift = run("go", "mod", "tidy", "-diff", cwd=module, capture=True, check=False)
        require(drift.returncode == 0 and not drift.stdout.strip(),
                f"go mod tidy would change {module.relative_to(ROOT).as_posix()}:\n{drift.stdout}{drift.stderr}")
    go("vet", "./...")
    packages = check_access()
    ARTIFACTS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="go-static-", dir=ARTIFACTS) as temporary:
        tools = build_tools(Path(temporary) / "bin", ("staticcheck",))
        run(tools["staticcheck"], "-checks", STATICCHECK_CHECKS, "-tests", "./...")
        version = run(tools["staticcheck"], "-version", capture=True).stdout.strip()
    identity = check_module_identity()
    return {"go": pinned, **modules, "sources": sources, "generatedPackages": packages, "staticcheck": version,
            "moduleIdentity": identity,
            "checks": ["toolchain", "module-inventory", "gofmt", "go-mod-verify", "go-mod-tidy-drift", "go-vet",
                       "contract-access-imports", "staticcheck", "module-identity"]}


def race_supported() -> bool:
    return platform.system() == "Linux"


def test(race: bool | None = None) -> dict:
    """go test of the published module with the fixtures and descriptors of this checkout (-race on Linux)."""
    pinned = check_toolchain()
    race = race_supported() if race is None else race
    write_descriptor(protoc_path(), go_row())
    flags = ["-race"] if race else []
    go("test", "-count=1", "-timeout", "15m", *flags, "./...", env=environment({ROOT_ENV: str(ROOT)}))
    return {"go": pinned, "race": race}


def vulncheck() -> dict:
    """govulncheck over the published module and over the pinned tools (go.sum-verified sources; vuln.go.dev)."""
    pinned = check_toolchain()
    ARTIFACTS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="go-vulncheck-", dir=ARTIFACTS) as temporary:
        tools = build_tools(Path(temporary) / "bin", ("govulncheck",))
        run(tools["govulncheck"], "./...")
        run(tools["govulncheck"], "tool", cwd=TOOLS)
        version = run(tools["govulncheck"], "-version", capture=True).stdout.strip().splitlines()
    return {"go": pinned, "govulncheck": version[:3]}


