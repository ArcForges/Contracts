def go_version(release: str) -> str:
    """The Go module version of a candidate version: v<release>; v2+ would need a /vN module path (refused)."""
    from contracts import version
    version(release)
    major = int(release.split(".", 1)[0])
    require(major <= 1, f"Go module {GO_MODULE} cannot carry major version {major}: a /v{major} module path needs a "
                        "reviewed module identity change before a formal v2+ release tags the Go module")
    return "v" + release


def hash1(files: list[tuple[str, bytes]]) -> str:
    """golang.org/x/mod/sumdb/dirhash Hash1 over (name, content) pairs."""
    summary = "".join(f"{hashlib.sha256(data).hexdigest()}  {name}\n" for name, data in sorted(files))
    return "h1:" + base64.b64encode(hashlib.sha256(summary.encode("utf-8")).digest()).decode("ascii")


def module_files(commit: str, root: Path = ROOT) -> list[tuple[str, bytes]]:
    """The files of the module zip the Go proxy builds from the tag: the committed tree of go/, without nested
    modules (go/tools) and vendor directories; links, submodules and export attributes are refused."""
    listing = subprocess.check_output(["git", "-C", str(root), "ls-tree", "-r", "-z", "--full-tree", commit, "--", "go"])
    entries = []
    for line in listing.decode("utf-8").split("\0"):
        if not line:
            continue
        meta, path = line.split("\t", 1)
        mode, kind, blob = meta.split()
        entries.append((mode, kind, blob, path))
    nested = {str(PurePosixPath(path).parent) for _, _, _, path in entries
              if path.endswith("/go.mod") and path != "go/go.mod"}
    selected = []
    for mode, kind, blob, path in entries:
        if any(path.startswith(directory + "/") for directory in nested):
            continue
        require(kind == "blob" and mode in {"100644", "100755"}, "Unsupported Git entry in the Go module: " + path)
        require("/vendor/" not in "/" + path, "Vendored sources are not part of the Go module: " + path)
        selected.append((path, blob))
    require(any(path == "go/go.mod" for path, _ in selected), "The commit has no go/go.mod")
    attributes = subprocess.run(["git", "-C", str(root), "check-attr", "--source", commit, "-z", "export-ignore",
                                 "export-subst", "--", *(path for path, _ in selected)],
                                check=True, capture_output=True).stdout.decode("utf-8").split("\0")
    for index in range(0, len(attributes) - 2, 3):
        require(attributes[index + 2] in {"unspecified", "unset"},
                f"{attributes[index]} sets {attributes[index + 1]}, which changes the Go module zip")
    contents = subprocess.run(["git", "-C", str(root), "cat-file", "--batch"], check=True, capture_output=True,
                              input="".join(blob + "\n" for _, blob in selected).encode("ascii")).stdout
    files, at = [], 0
    for path, blob in selected:
        header_end = contents.index(b"\n", at)
        sha, _, size = contents[at:header_end].decode("ascii").split()
        require(sha == blob, "git cat-file returned another object")
        start = header_end + 1
        files.append((path.removeprefix("go/"), contents[start:start + int(size)]))
        at = start + int(size) + 1
    return files


def module_identity(commit: str, release: str, root: Path = ROOT) -> dict:
    version = go_version(release)
    files = module_files(commit, root)
    go_mod_bytes = next(data for name, data in files if name == "go.mod")
    return {"module": GO_MODULE, "version": version, "tag": "go/" + version, "commit": commit,
            "zipHash": hash1([(f"{GO_MODULE}@{version}/{name}", data) for name, data in files]),
            "goModHash": hash1([("go.mod", go_mod_bytes)]), "files": len(files)}


def check_module_identity(release: str = "1.0.0-ci.0.0") -> dict:
    """The module identity the candidate records (module_identity) equals what the go command computes for this
    commit through its own VCS path, the one proxy.golang.org uses: a temporary bare repository holds the commit under
    the go/v<release> tag and stands in for github.com/ArcForges/Contracts (git url.insteadOf). Nothing leaves the
    host and no tag is created in this repository."""
    commit = subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()
    expected = module_identity(commit, release)
    ARTIFACTS.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="go-module-identity-", dir=ARTIFACTS) as temporary:
        stage = Path(temporary)
        repository = stage / "repository.git"
        subprocess.run(["git", "init", "-q", "--bare", str(repository)], check=True)
        subprocess.run(["git", "-C", str(repository), "fetch", "-q", "--no-tags",
                        "--upload-pack=git -c uploadpack.allowAnySHA1InWant=true upload-pack", str(ROOT), commit],
                       check=True)
        subprocess.run(["git", "-C", str(repository), "update-ref", "refs/tags/" + expected["tag"], commit], check=True)
        (stage / "work").mkdir()
        env = environment({"GOFLAGS": "-mod=mod", "GOPROXY": "direct", "GOPRIVATE": "github.com/ArcForges/Contracts",
                           "GOMODCACHE": str(stage / "modcache"), "GIT_CONFIG_COUNT": "1",
                           "GIT_CONFIG_KEY_0": f"url.{repository.as_uri()}.insteadOf",
                           "GIT_CONFIG_VALUE_0": "https://github.com/ArcForges/Contracts"})
        try:
            info = json.loads(go("mod", "download", "-json", f"{GO_MODULE}@{expected['version']}", cwd=stage / "work",
                                 capture=True, env=env))
        finally:
            go("clean", "-modcache", cwd=stage / "work", env=env)
    require(info.get("Sum") == expected["zipHash"] and info.get("GoModSum") == expected["goModHash"],
            f"The go command computes {info.get('Sum')} / {info.get('GoModSum')} for {expected['tag']}, the candidate "
            f"would record {expected['zipHash']} / {expected['goModHash']}")
    return {"commit": commit, "zipHash": expected["zipHash"], "goModHash": expected["goModHash"], "files": expected["files"]}


def candidate_document(row: dict, release: str, commit: str, dirty: bool) -> dict:
    """The candidate's Go module entry: the identity the tag must resolve to through the proxy and the checksum
    database; the packages and access are copied from the row."""
    identity = module_identity(commit, release)
    descriptor = ARTIFACTS / row["descriptor"]
    return {"format": CANDIDATE_FORMAT, **identity, "dirty": dirty, "contractAccess": row["access"],
            "channel": row["channel"], "requires": go_mod(MODULE)["requires"],
            "descriptorSha256": hashlib.sha256(descriptor.read_bytes()).hexdigest(),
            "goPackages": row["goPackages"]}


def verify_candidate(document: dict, row: dict, release: str, manifest: dict) -> None:
    require(document.get("format") == CANDIDATE_FORMAT, "Unknown Go module candidate format")
    expected = candidate_document(row, release, manifest["commit"], manifest["dirty"])
    require(document == expected, "Go module candidate differs from the checkout at the candidate commit")


def escape_path(value: str) -> str:
    """Go module proxy case encoding: every upper-case letter becomes '!' and its lower case."""
    return re.sub(r"[A-Z]", lambda match: "!" + match[0].lower(), value)


def http_json(method: str, url: str, token: str | None = None, body: dict | None = None,
              timeout: float = 60.0) -> tuple[int, object]:
    headers = {"User-Agent": "ArcForges-Contracts-CI", "Accept": "application/vnd.github+json",
               "X-GitHub-Api-Version": "2022-11-28"}
    if token:
        headers["Authorization"] = "Bearer " + token
    data = json.dumps(body).encode("utf-8") if body is not None else None
    if data is not None:
        headers["Content-Type"] = "application/json"
    try:
        with urlopen(Request(url, data=data, method=method, headers=headers), timeout=timeout) as response:
            payload = response.read()
            return response.status, json.loads(payload) if payload else None
    except HTTPError as error:
        payload = error.read()
        error.close()
        try:
            return error.code, json.loads(payload) if payload else None
        except ValueError:
            return error.code, None


def tag_target(repository: str, tag: str, token: str) -> str | None:
    """The commit an existing tag names (annotated tags are peeled), or None when the tag does not exist."""
    status, value = http_json("GET", f"https://api.github.com/repos/{repository}/git/ref/tags/{quote(tag, safe='/')}",
                              token)
    if status == 404:
        return None
    require(status == 200 and isinstance(value, dict) and value.get("ref") == "refs/tags/" + tag,
            f"Reading refs/tags/{tag} failed with HTTP {status}")
    target = value["object"]
    while target["type"] == "tag":
        status, tag_object = http_json("GET", f"https://api.github.com/repos/{repository}/git/tags/{target['sha']}",
                                       token)
        require(status == 200, f"Reading the annotated tag {tag} failed with HTTP {status}")
        target = tag_object["object"]
    require(target["type"] == "commit", f"refs/tags/{tag} does not name a commit")
    return target["sha"]


def create_tag(repository: str, tag: str, commit: str, token: str) -> str:
    """Create the immutable tag at commit; an existing tag is accepted only at the same commit, never moved."""
    existing = tag_target(repository, tag, token)
    if existing is None:
        status, _ = http_json("POST", f"https://api.github.com/repos/{repository}/git/refs", token,
                              {"ref": "refs/tags/" + tag, "sha": commit})
        if status == 201:
            say(f"Created {tag} at {commit}")
            return "created"
        require(status == 422, f"Creating refs/tags/{tag} failed with HTTP {status}")
        existing = tag_target(repository, tag, token)
    require(existing == commit, f"{tag} already exists at {existing}, not at the publishing commit {commit}; Go module "
                                "tags are immutable and are never moved or recreated")
    say(f"{tag} already names the publishing commit {commit}")
    return "existing"


def resolve(document: dict, budget: float = RESOLVE_BUDGET, first_wait: float = 15.0) -> dict:
    """The handoff: the public module proxy serves the tag at the publishing commit and the checksum database records
    the candidate's hashes. Metadata only; the module zip is not downloaded. Retries with growing waits while the proxy
    fetches, and gives up once the waits and requests would pass `budget` seconds."""
    import time
    module, version = escape_path(document["module"]), escape_path(document["version"])
    deadline = time.monotonic() + budget

    def remaining() -> float:
        return max(1.0, min(REQUEST_TIMEOUT, deadline - time.monotonic()))

    wait, last, attempt = first_wait, "no request made", 0
    while time.monotonic() + wait < deadline:
        time.sleep(wait)
        attempt += 1
        try:
            status, info = http_json("GET", f"{PROXY}/{module}/@v/{version}.info", timeout=remaining())
            if status == 200 and isinstance(info, dict):
                require(info.get("Version") == document["version"], "The proxy serves another version: " + str(info))
                origin = info.get("Origin") or {}
                require(not origin.get("Hash") or origin["Hash"] == document["commit"],
                        f"The proxy resolved {document['tag']} to {origin.get('Hash')}, not {document['commit']}")
                lookup = Request(f"{SUMDB}/lookup/{module}@{version}", headers={"User-Agent": "ArcForges-Contracts-CI"})
                with urlopen(lookup, timeout=remaining()) as response:
                    lines = response.read().decode("utf-8").splitlines()
                recorded = {}
                for line in lines:
                    parts = line.split()
                    if len(parts) == 3 and parts[0] == document["module"]:
                        recorded[parts[1]] = parts[2]
                require(recorded.get(document["version"]) == document["zipHash"]
                        and recorded.get(document["version"] + "/go.mod") == document["goModHash"],
                        f"The checksum database records other hashes for {document['module']}@{document['version']}: "
                        f"{recorded}; expected {document['zipHash']} and {document['goModHash']}")
                return {"proxy": info, "checksumDatabase": recorded, "attempts": attempt}
            last = f"HTTP {status}"
        except (URLError, TimeoutError, ConnectionError) as problem:
            last = str(problem)
        say(f"The module proxy does not serve {document['tag']} yet ({last}); attempt {attempt}, "
            f"{max(0.0, deadline - time.monotonic()):.0f} s of {budget:.0f} s left")
        wait = min(wait * 2, 120.0)
    raise ValueError(f"The module proxy did not resolve {document['module']}@{document['version']} within "
                     f"{budget:.0f} s ({attempt} attempts; last: {last}). The tag {document['tag']} exists at "
                     f"{document['commit']}, so diagnose the proxy and checksum database responses before rerunning "
                     "this job (the rerun keeps the tag)")


def publish(directory: Path, manifest: dict, entry: dict) -> None:
    """Tag go/v<version> at the publishing commit after the NuGet cohort published, then resolve it once."""
    from release_channels import authorize
    authorize(manifest["version"])
    document = json.loads((directory / entry["name"]).read_text(encoding="utf-8"))
    commit = os.environ.get("GITHUB_SHA", "")
    require(document.get("format") == CANDIDATE_FORMAT and document["module"] == GO_MODULE
            and document["version"] == go_version(manifest["version"]) and document["tag"] == "go/" + document["version"]
            and document["commit"] == commit == manifest["commit"] and not document["dirty"],
            "The Go module candidate does not describe this publishing commit and version")
    token = os.environ.get("GITHUB_TOKEN")
    require(bool(token), "Tagging needs the job's GITHUB_TOKEN with contents: write")
    outcome = create_tag(os.environ["GITHUB_REPOSITORY"], document["tag"], commit, token)
    handoff = resolve(document)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as stream:
            stream.write(f"\ngo: {document['tag']} {outcome} at {commit}; proxy.golang.org serves "
                         f"{document['module']}@{document['version']} and sum.golang.org records "
                         f"{document['zipHash']}.\n")
    say(json.dumps({"tag": document["tag"], "outcome": outcome, "handoff": handoff}, default=str))


