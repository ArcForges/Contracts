def exchange_model(row: dict):
    import check_compatibility as compatibility
    return compatibility, compatibility.descriptor((ARTIFACTS / row["descriptor"]).read_bytes())


def map_entries(model: dict) -> set[str]:
    """protoc's map entry convention: nested <Field>Entry with key 1 and value 2, used by one repeated field."""
    entries = set()
    for parent, fields in model["messages"].items():
        for field in fields.values():
            name = field["typeName"]
            if field["type"] == 11 and field["label"] == 3 and name.startswith(parent + ".") and name.endswith("Entry"):
                inner = model["messages"].get(name, {})
                if set(inner) == {1, 2} and inner[1]["name"] == "key" and inner[2]["name"] == "value":
                    entries.add(name)
    return entries


def map_sample(model: dict, entries: set[str], name: str, tree: dict) -> dict:
    """A reference sample as a map-aware runtime can hold it: a map entry keeps no unknown member (protobuf
    runtimes drop it), and the two synthesized entries of a map get distinct keys in ascending order (the same key
    twice would collapse to one entry), so every runtime writes them back in the order the reference expects."""
    result = {}
    for tag, value in tree.items():
        field = model["messages"][name].get(tag) if tag != "?" else None
        if field is not None and field["type"] == 11:
            items = value if field["label"] == 3 else [value]
            items = [map_sample(model, entries, field["typeName"], item) for item in items]
            if field["typeName"] in entries:
                for index, item in enumerate(items):
                    key = item.get(1)
                    item[1] = (("A" if index == 0 else "B") + "-" + key if isinstance(key, str) else key + index)
                keys = [item[1] for item in items]
                require(keys == sorted(set(keys)), f"{name}.{field['name']}: map sample keys are not distinct")
            value = items if field["label"] == 3 else items[0]
        result[tag] = value
    if name in entries:
        result.pop("?", None)
    return result


def exchange_samples(compatibility, model: dict) -> list[tuple[str, dict]]:
    entries = map_entries(model)
    samples = []
    for name in sorted(model["messages"]):
        if name in entries:
            continue
        for sample in compatibility.sample_ids(model, name):
            tree = compatibility.synthesize_sample(model, sample)
            samples.append((sample.lstrip("."), map_sample(model, entries, name, tree)))
    return samples


def emit_exchange(directory: Path) -> int:
    """Reference-codec bytes of every sample of every message of the Go module, for the C# codecs to rewrite."""
    row = go_row()
    compatibility, model = exchange_model(row)
    target = directory / EXCHANGE
    (target / "previous").mkdir(parents=True, exist_ok=True)
    samples = exchange_samples(compatibility, model)
    for sample, tree in samples:
        data = compatibility.encode_message(model, "." + sample.partition("@")[0], tree)
        (target / "previous" / (sample + ".bin")).write_bytes(data)
    (target / "messages.txt").write_text("\n".join(sample for sample, _ in samples) + "\n", encoding="utf-8",
                                         newline="\n")
    (target / "files.txt").write_text("\n".join(source.split("/proto/", 1)[1] for source in row["proto"]) + "\n",
                                      encoding="utf-8", newline="\n")
    return len(samples)


def verify_exchange(directory: Path) -> dict:
    """Every sample the C# codecs rewrote and the Go codecs rewrote again keeps its meaning for the reference reader;
    the C# file list equals the Go module's proto files; Go and C# bytes are compared."""
    row = go_row()
    compatibility, model = exchange_model(row)
    target = directory / EXCHANGE
    errors, identical, total = [], 0, 0
    listed = (target / "messages.txt").read_text(encoding="utf-8").split()
    expected = exchange_samples(compatibility, model)
    if listed != [sample for sample, _ in expected]:
        errors.append("the sample list differs from the Go module descriptor")
    csharp_files = (target / "csharp-files.txt").read_text(encoding="utf-8").split()
    if sorted(csharp_files) != sorted(source.split("/proto/", 1)[1] for source in row["proto"]):
        errors.append("the C# leg did not read exactly the Go module's proto files")
    for sample, tree in expected:
        name = "." + sample.partition("@")[0]
        try:
            csharp = (target / "current" / (sample + ".bin")).read_bytes()
            go_bytes = (target / "go" / (sample + ".bin")).read_bytes()
            for label, data in (("C#", csharp), ("Go", go_bytes)):
                if compatibility.decode_message(model, name, data) != tree:
                    errors.append(f"{sample}: the reference reader sees a different meaning in the {label} bytes")
            identical += go_bytes == csharp
            total += 1
        except (OSError, ValueError, UnicodeDecodeError, KeyError) as problem:
            errors.append(f"{sample}: {problem}")
    fixtures = json.loads((target / "fixtures" / "index.json").read_text(encoding="utf-8"))
    checked = json.loads((target / "fixtures" / "go-checked.json").read_text(encoding="utf-8"))
    if checked != [item["id"] for item in fixtures] or not fixtures:
        errors.append("the Go leg did not check every C#-encoded fixture case")
    fixture_identical = sum((target / "fixtures" / item["file"]).read_bytes()
                            == (target / "fixtures" / ("go-" + item["file"])).read_bytes() for item in fixtures)
    return {"schemaVersion": "contract-go-codec-exchange.v1", "messages": len({s.partition('@')[0] for s, _ in expected}),
            "samples": total, "byteIdenticalWithCSharp": identical, "fixtureCases": len(fixtures),
            "fixtureCasesByteIdentical": fixture_identical,
            "byteOrderNote": "protobuf-go writes non-synthetic oneof members after the other fields; C# writes field "
                             "number order. Both are valid encodings with the same meaning, checked in both directions.",
            "errorCount": len(errors), "errors": errors[:100]}


def exchange() -> dict:
    """Reference codec -> C# generated codecs -> Go generated codecs -> reference reader, for every message and every
    oneof arm of the Go module, plus the C# encoding of every positive foundation fixture case; offline files only."""
    check_toolchain()
    row = go_row()
    write_descriptor(protoc_path(), row)
    structure_tests = ROOT / "tests/StructureTests/bin/Release/net10.0/StructureTests.dll"
    require(structure_tests.is_file(), "Build the solution first (python eng/contracts.py build or pack)")
    with tempfile.TemporaryDirectory(prefix="arcforges-go-exchange-") as temporary:
        directory = Path(temporary)
        count = emit_exchange(directory)
        say(f"Wrote {count} reference-codec samples of the Go module's messages")
        run("dotnet", structure_tests, ROOT, "--go-exchange", directory / EXCHANGE, cwd=ROOT, env=dict(os.environ))
        go("test", "-count=1", "-v", "-run", "^TestCSharpExchange$", "./internal/compat/",
           env=environment({ROOT_ENV: str(ROOT), EXCHANGE_ENV: str(directory / EXCHANGE)}))
        run("dotnet", structure_tests, ROOT, "--go-exchange-verify", directory / EXCHANGE, cwd=ROOT, env=dict(os.environ))
        report = verify_exchange(directory)
    evidence = ARTIFACTS / "evidence" / "go-exchange.json"
    evidence.parent.mkdir(parents=True, exist_ok=True)
    evidence.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    say(json.dumps({key: value for key, value in report.items() if key != "errors"}))
    require(report["errorCount"] == 0, "The Go/C# exchange failed:\n" + "\n".join(report["errors"]))
    return report


def check_all(with_vulncheck: bool = True) -> dict:
    """Every Go check. ci.yml leaves govulncheck out on main and v* pushes, which run delivery only; the host
    verification, external-PR CI and the weekly security run keep it (docs/engineering-controls.md)."""
    result = {"static": static(), "test": test(), "exchange": exchange(),
              "vulncheck": vulncheck() if with_vulncheck else "not run (--no-vulncheck)"}
    evidence = ARTIFACTS / "evidence" / "go-checks.json"
    evidence.parent.mkdir(parents=True, exist_ok=True)
    evidence.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


